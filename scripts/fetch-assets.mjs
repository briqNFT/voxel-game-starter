// Re-fetch every asset in assets.json from briq and regenerate CREDITS.md.
//
// briq's /download URLs are permanent and keyless for free assets; each hit
// 302-redirects to a storage URL that expires in an hour, which is why the
// files are vendored into public/assets/ instead of hotlinked. Run this after
// editing assets.json (e.g. swapping the character for another briq-v1 one).
//
//   npm run assets

import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const manifest = JSON.parse(await readFile(join(root, "public", "assets.json"), "utf8"));
const outDir = join(root, "public", "assets");
await mkdir(outDir, { recursive: true });

const entries = [manifest.character, ...manifest.props];
const credits = [];

for (const entry of entries) {
  const base = `${manifest.api}/assets/${entry.id}/download?format=glb&variant=${entry.variant}`;

  const meta = await fetch(`${base}&meta=1`, { headers: { "User-Agent": "voxel-game-starter" } });
  if (!meta.ok) {
    const body = await meta.json().catch(() => ({}));
    throw new Error(`${entry.id}: ${meta.status} ${body.error?.code ?? ""} ${body.error?.message ?? ""}`.trim());
  }
  const { data } = await meta.json();

  const file = await fetch(data.download_url, { headers: { "User-Agent": "voxel-game-starter" } });
  if (!file.ok) throw new Error(`${data.asset.title}: download failed with ${file.status}`);
  await writeFile(join(outDir, entry.file), Buffer.from(await file.arrayBuffer()));

  credits.push(`- ${data.attribution}`);
  console.log(`fetched ${entry.file.padEnd(18)} ${String(data.size_bytes).padStart(8)} B  ${data.asset.title} (${data.license.code})`);
}

await writeFile(
  join(root, "CREDITS.md"),
  [
    "# Credits",
    "",
    "3D assets from [briq](https://briq.market), each under the Creative Commons license its creator chose.",
    "CC BY requires this credit to ship with the game; CC0 would not, but it costs nothing to say thanks.",
    "",
    ...credits,
    "",
    "Regenerated by `npm run assets` from assets.json.",
    "",
  ].join("\n"),
);
console.log("wrote CREDITS.md");
